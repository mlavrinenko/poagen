<?php

declare(strict_types=1);

namespace Mlavrinenko\Paogen\Generator\Emit;

use Mlavrinenko\Paogen\Generator\Profile;
use RuntimeException;

use function strlen;

/**
 * The comment block every emitted file opens with.
 *
 * `never-edit-generated` was a rule written down somewhere else — in
 * `AGENT.md`, in a standard, in a task — and a file that says nothing about
 * itself cannot carry it. The header moves the rule into the artifact: it
 * survives a clone, it shows up in a diff, and it is the first thing both a
 * reader and an agent see when they open the file they were about to edit.
 *
 * Everything in it is derived from the profile, so two runs over the same
 * inputs stamp the same bytes. No timestamp, no version, no absolute path —
 * each of those would make a re-run a diff (`cheap-regeneration`).
 */
final readonly class GeneratedFileHeader
{
    private const string OPENING_TAG = "<?php\n";

    /**
     * @param string $profile Path to the profile that produced the file, as
     *                        the reader would type it: relative to the
     *                        directory the run was invoked from. See
     *                        {@see Profile::$source}.
     */
    public function __construct(private string $profile) {}

    /**
     * Insert the header between the opening tag and the rest of the file.
     *
     * The emitters all print through nette's `PsrPrinter`, which always opens
     * with `<?php` on its own line; a caller handing over anything else is a
     * bug in the emitter rather than a file to stamp best-effort, so this
     * throws instead of prepending a header to something that is not PHP.
     */
    public function stamp(string $code): string
    {
        if (!str_starts_with($code, self::OPENING_TAG)) {
            throw new RuntimeException('Cannot stamp a generated header onto output that does not open with a PHP tag.');
        }

        return self::OPENING_TAG . "\n" . $this->render() . substr($code, strlen(self::OPENING_TAG));
    }

    /**
     * Line comments rather than a doc block on purpose. A doc block in this
     * position is PHPDoc attached to whatever follows it, so both a reader and
     * a static analyser would read the notice as documentation of the emitted
     * class rather than of the file.
     */
    private function render(): string
    {
        return "// Generated by paogen. Do not edit by hand: the next run rewrites this\n"
            . "// file whole and any hand edit goes with it. Change the schema or the\n"
            . "// profile instead.\n"
            . "//\n"
            . "// Profile:    {$this->profile}\n"
            . "// Regenerate: paogen generate {$this->profile}\n";
    }
}
